using System.IO;
using System.Text;
using AxuTestFramework.Core.Baseline;
using AxuTestFramework.Core.Report;

namespace AxuTestFramework.Editor.Export
{
    /// <summary>
    /// ScenarioReport → 单文件自包含 HTML 摘要导出器（方案 §6.2：供邮件/群发的轻量结果页）。
    /// <para>内联 CSS（零外部依赖零脚本）：顶部 suite 信息（id/起止时间/退出码/汇总/环境要点），
    /// 主体为逐 scenario 表格（capability / status / durationMs / 关键指标 / 预算结论 / findings 数）。
    /// 指标经 <see cref="BaselineDiff.Flatten"/> 扁平化（与趋势 CSV 同键），全部转义防注入。</para>
    /// </summary>
    public static class HtmlSummaryExporter
    {
        /// <summary>导出为自包含 HTML 字符串。</summary>
        public static string Export(ScenarioReport report, string suiteId)
        {
            var suite = string.IsNullOrEmpty(suiteId) ? report?.SuiteId : suiteId;
            var sb = new StringBuilder();
            sb.Append("<!DOCTYPE html>\n<html lang=\"zh\">\n<head>\n<meta charset=\"utf-8\">\n");
            sb.Append("<title>AxuTestFramework — ").Append(Escape(suite ?? "(unknown suite)")).Append("</title>\n");
            sb.Append(Style);
            sb.Append("</head>\n<body>\n");

            sb.Append("<h1>AxuTestFramework Suite 报告</h1>\n");
            sb.Append("<table class=\"meta\">");
            AppendMeta(sb, "Suite", suite);
            AppendMeta(sb, "开始 / 结束", $"{report?.StartedAt ?? "-"} → {report?.EndedAt ?? "-"}");
            AppendMeta(sb, "退出码", $"{(int?)(report?.ExitCode ?? 0)}（{ExitCodeText(report)}）");
            var summary = report?.Summary;
            AppendMeta(sb, "汇总", summary != null
                ? $"total {summary.Total} · pass {summary.Passed} · warn {summary.Warned} · fail {summary.Failed}"
                : "（无汇总）");
            AppendMeta(sb, "环境", EnvironmentLine(report?.Environment));
            sb.Append("</table>\n");

            sb.Append("<table class=\"grid\">\n<tr>" +
                      "<th>Scenario</th><th>Capability</th><th>Status</th><th>DurationMs</th>" +
                      "<th>关键指标</th><th>预算结论</th><th>Findings</th></tr>\n");

            if (report?.Results != null)
            {
                foreach (var result in report.Results)
                {
                    if (result == null) continue;
                    var status = (result.Status ?? "-").Trim().ToLowerInvariant();
                    sb.Append("<tr>");
                    sb.Append($"<td>{Escape(result.ScenarioId)}</td>");
                    sb.Append($"<td>{Escape(result.Capability ?? "-")}</td>");
                    sb.Append($"<td><span class=\"badge {StatusClass(status)}\">{Escape(result.Status ?? "-")}</span></td>");
                    sb.Append($"<td class=\"num\">{result.DurationMs:0.#}</td>");
                    sb.Append($"<td class=\"metrics\">{Escape(MetricsLine(result))}</td>");
                    sb.Append($"<td>{Escape(BudgetLine(result))}</td>");
                    sb.Append($"<td class=\"num\">{CountFindings(result)}</td>");
                    sb.Append("</tr>\n");
                }
            }
            sb.Append("</table>\n");
            sb.Append("<p class=\"foot\">generated by AxuTestFramework.HtmlSummaryExporter</p>\n");
            sb.Append("</body>\n</html>\n");
            return sb.ToString();
        }

        /// <summary>导出并写盘（自动建目录，UTF-8 无 BOM），返回写入路径。</summary>
        public static string ExportToFile(ScenarioReport report, string suiteId, string path)
        {
            var directory = Path.GetDirectoryName(path);
            if (!string.IsNullOrEmpty(directory) && !Directory.Exists(directory))
                Directory.CreateDirectory(directory);
            File.WriteAllText(path, Export(report, suiteId), new UTF8Encoding(false));
            return path;
        }

        const string Style = @"
<style>
:root { color-scheme: dark; }
body { font: 13px/1.5 -apple-system, 'Segoe UI', sans-serif; background: #141414; color: #e8e8e8; margin: 24px; }
h1 { font-size: 18px; border-bottom: 1px solid #3a3a3a; padding-bottom: 8px; }
table { border-collapse: collapse; margin-top: 12px; }
.meta td { padding: 3px 12px 3px 0; color: #a0a0a0; vertical-align: top; }
.meta td:first-child { color: #6e6e6e; white-space: nowrap; }
.meta td:last-child { color: #e8e8e8; }
.grid th, .grid td { border: 1px solid #262626; padding: 6px 10px; text-align: left; vertical-align: top; }
.grid th { background: #1e1e1e; color: #a0a0a0; font-size: 12px; }
.grid tr:nth-child(even) td { background: #1a1a1a; }
.num { text-align: right; font-variant-numeric: tabular-nums; }
.metrics { max-width: 360px; font-size: 12px; color: #c8c8c8; }
.badge { display: inline-block; padding: 1px 8px; border-radius: 9px; font-size: 12px; }
.pass { background: rgba(92,184,92,.16); color: #8ed19a; }
.warn { background: rgba(255,193,7,.14); color: #ffc107; }
.fail, .error { background: rgba(224,82,82,.16); color: #ec8a8a; }
.foot { color: #6e6e6e; font-size: 11px; margin-top: 16px; }
</style>
";

        static string MetricsLine(ScenarioReportResult result)
        {
            if (result.Metrics == null) return "（无指标）";
            var parts = new StringBuilder();
            foreach (var flat in BaselineDiff.Flatten(result.Metrics))
            {
                if (parts.Length > 0) parts.Append("  ·  ");
                parts.Append(flat.Key).Append(" = ").Append(flat.Value.ToString("0.###"));
                if (parts.Length > 400) { parts.Append(" …"); break; }
            }
            return parts.Length == 0 ? "（无指标）" : parts.ToString();
        }

        static string BudgetLine(ScenarioReportResult result)
        {
            if (result.Budgets == null || result.Budgets.Count == 0)
                return result.Unbudgeted ? "未配置（unbudgeted）" : "无预算";
            var pass = 0; var warn = 0; var fail = 0;
            foreach (var budget in result.Budgets)
            {
                if (budget == null) continue;
                switch ((budget.Verdict ?? string.Empty).Trim().ToLowerInvariant())
                {
                    case "pass": pass++; break;
                    case "warn": warn++; break;
                    default: fail++; break;
                }
            }
            return $"{pass} pass / {warn} warn / {fail} fail";
        }

        static int CountFindings(ScenarioReportResult result)
        {
            var count = 0;
            if (result.Findings != null)
                foreach (var finding in result.Findings)
                    if (finding != null) count++;
            return count;
        }

        static string EnvironmentLine(ScenarioEnvironment env)
        {
            if (env == null) return "（无环境信息）";
            var parts = new StringBuilder();
            if (!string.IsNullOrEmpty(env.UnityVersion)) parts.Append("Unity ").Append(env.UnityVersion);
            if (!string.IsNullOrEmpty(env.Os)) parts.Append(" · ").Append(env.Os);
            if (!string.IsNullOrEmpty(env.DeviceModel)) parts.Append(" · ").Append(env.DeviceModel);
            if (!string.IsNullOrEmpty(env.GraphicsDevice)) parts.Append(" · ").Append(env.GraphicsDevice);
            if (env.IsEditor.HasValue) parts.Append(env.IsEditor.Value ? " · Editor" : " · Player");
            if (env.DevelopmentBuild.HasValue && env.DevelopmentBuild.Value) parts.Append(" · DevBuild");
            return parts.Length == 0 ? "（无环境信息）" : parts.ToString();
        }

        static string ExitCodeText(ScenarioReport report)
        {
            switch (report?.ExitCode ?? ScenarioExitCode.Success)
            {
                case ScenarioExitCode.Failures: return "存在 fail";
                case ScenarioExitCode.WarningsOnly: return "仅 warn";
                case ScenarioExitCode.InfrastructureError: return "基础设施错误";
                default: return "全部 pass";
            }
        }

        static string StatusClass(string status)
        {
            switch (status)
            {
                case "pass": return "pass";
                case "warn": return "warn";
                case "fail":
                case "error": return "fail";
                default: return "warn";
            }
        }

        static void AppendMeta(StringBuilder sb, string key, string value)
        {
            sb.Append($"<tr><td>{Escape(key)}</td><td>{Escape(value ?? "-")}</td></tr>");
        }

        static string Escape(string text)
        {
            if (string.IsNullOrEmpty(text)) return string.Empty;
            var sb = new StringBuilder(text.Length);
            foreach (var c in text)
            {
                switch (c)
                {
                    case '<': sb.Append("&lt;"); break;
                    case '>': sb.Append("&gt;"); break;
                    case '&': sb.Append("&amp;"); break;
                    case '"': sb.Append("&quot;"); break;
                    default: sb.Append(c); break;
                }
            }
            return sb.ToString();
        }
    }
}
